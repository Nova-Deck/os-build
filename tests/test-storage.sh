CASE="the-probes-garbage-is-cleared-where-it-is-made"
# Upstream zeroes the first sectors right after the probe, and its reason stands on its own:
# "Otherwise parted may think we have existing partitions in a bogus state". f3probe --destructive
# writes across the whole device, so what it leaves behind can read as a partition table to whatever
# looks next.
#
# IT IS NOT WHAT FIXED THE FAILED UNIT AFTER EVERY FORMAT. That was the missing lock, established
# afterwards by measurement. This was the second of three attempts at that symptom, and it survives
# only because upstream does it for a reason of its own. The retry it replaced does not survive.
code "$FMT" | grep -qE 'dd if=/dev/zero of="\$DEVICE" bs=512 count=1024' \
  && ok "the formatter zeroes the sectors f3probe scribbled on" \
  || bad "f3probe's garbage is left in place — udev will read it as a filesystem"
probe_ln=$(grep -nE '^ *probe_out=' "$FMT" | head -1 | cut -d: -f1)
dd_ln=$(grep -nE '^ *dd if=/dev/zero' "$FMT" | head -1 | cut -d: -f1)
wipe_ln=$(grep -nE '^[^#]*wipefs' "$FMT" | head -1 | cut -d: -f1)
[ -n "$probe_ln" ] && [ -n "$dd_ln" ] && [ -n "$wipe_ln" ] && [ "$probe_ln" -lt "$dd_ln" ] && [ "$dd_ln" -lt "$wipe_ln" ] \
  && ok "and does it between the probe (line $probe_ln) and the first wipefs (line $wipe_ln)" \
  || bad "the zeroing is not between the probe and the format — that ordering is the whole point"
# NO RETRY IN THE MOUNTER. It was there for this symptom; a failure now names its own reason and
# fails, which is what makes the next unexplained one findable instead of merely quiet.
code "$AUTO" | grep -qE 'tries|sleep 0\.5' \
  && bad "the mount retry is back — it existed only to mask f3probe's leftovers" \
  || ok "the mounter makes one call and reports what it got"

