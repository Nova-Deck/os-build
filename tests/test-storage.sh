#!/usr/bin/env bash
# Offline test for the removable-storage surface — the pieces that let an SD card be adopted as a
# Steam library (issue #42).
#
#   tests/test-storage.sh
#
# WHY THIS FILE EXISTS. The whole surface is declarations: a package name in a list, a lock row, a
# polkit rule granting some action ids and — the part that matters — deliberately NOT granting
# others. None of that fails loudly when it drifts. A package added to PKGS but never relocked
# ships nothing; a rule that grows a format action before anything refuses formatting the boot disk
# is a card-shaped hole in the running system. Both are exactly the shape rootfs/guard-rootfs.sh
# exists for on the built tree, and both are checkable here, on the sources, in milliseconds.
#
# WHAT THIS CANNOT COVER: whether udisksd actually answers, whether the client's Storage page
# enumerates anything, and whether an inserted card mounts. Those need a device with a spare card,
# which is what internal installation made possible — see the checklist on #42.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PKGSRC="$ROOT/rootfs/customize-base.sh"
LOCK="$ROOT/rootfs/manifest.lock"
RULES="$ROOT/rootfs/overlay/usr/share/polkit-1/rules.d/50-novadeck-storage.rules"

PASS=0; FAIL=0; CASE=""
ok()  { PASS=$((PASS+1)); printf '  ok   %s -- %s\n' "$CASE" "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  FAIL %s -- %s\n' "$CASE" "$1"; }

# =================================================================================================
CASE="udisks2-is-declared-and-locked"
# THE PAIR, not either half. PKGS is the declaration and manifest.lock is what the base actually
# installs, and they are regenerated by different commands (`make relock`). A PKGS entry with no
# lock row is a package the image does not have, which is precisely the state that made Settings >
# Storage enumerate nothing in the first place.
for p in udisks2 f3; do
  grep -qE "[( ]$p[) ]" "$PKGSRC" \
    && ok "$p is in PKGS" \
    || bad "$p is not declared in ${PKGSRC#"$ROOT"/}"
  grep -qE "^$p " "$LOCK" \
    && ok "$p has a row in manifest.lock (the base really installs it)" \
    || bad "no $p row in ${LOCK#"$ROOT"/} — declared but never relocked, so the image ships nothing"
done

# f3 is not in any repo we consume (it is an AUR package), so it can only come from the overlay —
# and an overlay package is a source.pin plus the PKGBUILD it names. A PKGS entry with neither is a
# package the resolver cannot find at all.
[ -f "$ROOT/packages/f3/source.pin" ] && [ -f "$ROOT/packages/f3/PKGBUILD" ] \
  && ok "f3 has an overlay source.pin and a local PKGBUILD" \
  || bad "f3 is in PKGS with no overlay package to build it from"
grep -q 'build/f3probe' "$ROOT/packages/f3/PKGBUILD" \
  && ok "and builds only f3probe (f3fix is what would drag parted onto the image)" \
  || bad "the PKGBUILD builds more than f3probe — check what it links before accepting that"

# =================================================================================================
CASE="storage-polkit-rule"
[ -f "$RULES" ] && ok "the rule ships" || bad "missing: ${RULES#"$ROOT"/}"

# The gate, not just the grants. Without the active+wheel test the rule would authorize any subject
# that can reach the bus, including a non-session one.
grep -q 'subject.active' "$RULES" && grep -q 'isInGroup("wheel")' "$RULES" \
  && ok "gated on an active session in wheel, like 50-novadeck-timezone.rules" \
  || bad "the rule does not gate on subject.active + wheel"

# THE QUOTED STRINGS WITH THE COMMENTS STRIPPED, never a grep over the whole file. This rule
# NAMES the actions it deliberately withholds, in prose, immediately above the ones it grants — so
# a plain grep answers "is this word in the file", which is yes for both halves and is how the
# negative case below would pass while asserting nothing.
granted() { sed 's,//.*,,' "$RULES" | grep -oE '"[A-Za-z0-9._-]+"' | tr -d '"'; }

for act in filesystem-unmount-others eject-media eject-media-other-seat \
           power-off-drive power-off-drive-other-seat; do
  granted | grep -qx "org.freedesktop.udisks2.$act" \
    && ok "grants $act" \
    || bad "does not grant $act — the client's release path fails with a silent bus refusal"
done

# =================================================================================================
CASE="nothing-that-writes-a-device-is-granted"
# THE REFUSALS LIVE IN THE HELPER, so the bus must not offer a way around them. format-device.sh
# checks that a disk is a removable SD this system is not running from before it writes anything,
# and granting the shell org.freedesktop.udisks2.format-device or modify-device would let the client
# repartition a disk through udisks directly with none of that applied.
#
# The reason this case was FIRST written is spent — "nothing refuses formatting the boot disk yet"
# was true then and is not now — but the grant is still wrong, for the reason above.
#
# filesystem-mount is absent for a different reason and is NOT a defect: stock udisks2 policy
# already allows it for an active session, so listing it would make this file claim to do something
# it does not do.
for act in modify-device format-device run-steamos-polkit-helpers-steamos-format-sdcard \
           run-steamos-polkit-helpers-steamos-format-device; do
  granted | grep -q -- "$act" \
    && bad "$act is granted — see #42: nothing refuses formatting the boot disk yet" \
    || ok "$act is not granted"
done

# =================================================================================================
CASE="rule-is-syntactically-whole"
# Not a JS parser — a brace/bracket balance and a terminator. A truncated polkit rule does not fail
# loudly: polkitd logs a parse error to the journal and CARRIES ON with the rule absent, which
# reads on the device as "the grant silently does not work".
awk '{o+=gsub(/[{[]/,"&"); c+=gsub(/[}\]]/,"&")} END{exit !(o==c && o>0)}' "$RULES" \
  && ok "braces and brackets balance" \
  || bad "unbalanced braces/brackets — polkitd would drop the whole rule with only a journal line"
grep -q '^});' "$RULES" \
  && ok "addRule() is closed" \
  || bad "the addRule() call is not terminated"

# =================================================================================================
CASE="the-scripts-ship-and-parse"
LIB="$ROOT/rootfs/overlay/usr/lib/novadeck/storage/lib-storage.sh"
FMT="$ROOT/rootfs/overlay/usr/lib/novadeck/storage/format-device.sh"
AUTO="$ROOT/rootfs/overlay/usr/lib/novadeck/storage/automount.sh"
EVT="$ROOT/rootfs/overlay/usr/lib/novadeck/storage/block-event.sh"
POLICY="$ROOT/rootfs/overlay/usr/share/polkit-1/actions/org.novadeck.policykit.storage.policy"
UDEV="$ROOT/rootfs/overlay/usr/lib/udev/rules.d/99-novadeck-automount.rules"
UNIT="$ROOT/rootfs/overlay/usr/lib/systemd/system/novadeck-automount@.service"
H_SD="$ROOT/rootfs/overlay/usr/bin/steamos-polkit-helpers/steamos-format-sdcard"
H_DEV="$ROOT/rootfs/overlay/usr/bin/steamos-polkit-helpers/steamos-format-device"

# EVERY HELPER THE CLIENT CAN RUN LEAVES A LINE. pkexec records what it EXECUTED, so a call it
# declines leaves nothing, and steamos-update is not pkexec'd at all — so an invocation of it was
# invisible. "The client never called us" and "the client called us and it went nowhere" then look
# identical from the device, which is exactly the ambiguity that stalled the validation question.
for h in "$H_SD" "$H_DEV" "$ROOT/rootfs/overlay/usr/bin/steamos-polkit-helpers/steamos-update"; do
  grep -q 'logger -t' "$h" \
    && ok "$(basename "$h") records its own invocation" \
    || bad "$(basename "$h") runs silently — a call to it cannot be distinguished from no call"
done

for f in "$LIB" "$FMT" "$AUTO" "$EVT" "$H_SD" "$H_DEV"; do
  n="${f#"$ROOT"/}"
  [ -f "$f" ] || { bad "missing: $n"; continue; }
  bash -n "$f" 2>/dev/null && ok "$(basename "$f") parses" || bad "$n is not valid bash"
  # THE EXEC BIT IS PART OF THE ARTIFACT. The overlay is copied with its modes, and a script that
  # ships 0644 fails at the moment udev or the client runs it — the OOBE black screen was exactly
  # this, a lost exec bit that nothing checked.
  [ -x "$f" ] && ok "$(basename "$f") is executable" || bad "$n is not executable"
done
for f in "$POLICY" "$UDEV" "$UNIT"; do
  [ -f "$f" ] && ok "$(basename "$f") ships" || bad "missing: ${f#"$ROOT"/}"
done

# =================================================================================================
CASE="pkexec-action-matches-the-script"
# THE HIGHEST-VALUE ASSERTION IN THIS FILE. pkexec picks the action whose exec.path annotation
# equals the program being run; if the annotation and the helper's target ever drift apart, pkexec
# silently falls back to org.freedesktop.policykit.exec, which is auth_admin. On a device where no
# account has a password that is not a prompt — it is a Format button that does nothing, with no
# error anywhere. A string comparison here is the only thing that catches it.
annot="$(sed -n 's/.*exec\.path">\([^<]*\)<.*/\1/p' "$POLICY" | head -1)"
target="$(sed -n 's/.*pkexec \([^ ]*format-device\.sh\).*/\1/p' "$H_SD" | head -1)"
[ -n "$annot" ] && [ "$annot" = "$target" ] \
  && ok "the action annotates exactly what the helper execs ($annot)" \
  || bad "annotation '$annot' != helper target '$target' — pkexec would fall back to auth_admin"
[ "$annot" = "/usr/lib/novadeck/storage/format-device.sh" ] \
  && ok "and that is the shipped path" \
  || bad "the annotated path is not where the script ships"
grep -q "<allow_active>yes</allow_active>" "$POLICY" \
  && ok "allow_active=yes (the seat session may format)" \
  || bad "allow_active is not yes — the seat session could not format"
grep -q "<allow_inactive>no</allow_inactive>" "$POLICY" && grep -q "<allow_any>no</allow_any>" "$POLICY" \
  && ok "inactive and any are refused (an SSH login cannot wipe a card)" \
  || bad "allow_inactive/allow_any are not both no"

# =================================================================================================
CASE="both-paths-apply-the-same-refusals"
# The formatter and the mounter must agree about what a card is. They share lib-storage.sh for
# exactly that reason, and this asserts neither has grown its own answer.
for f in "$FMT" "$AUTO"; do
  n="$(basename "$f")"
  grep -q 'storage_is_sd' "$f" && grep -q 'storage_is_system_disk' "$f" \
    && ok "$n applies both predicates" \
    || bad "$n does not apply the SD + system-disk predicates"
  grep -q 'lib-storage.sh' "$f" \
    && ok "$n sources the shared library" \
    || bad "$n does not source lib-storage.sh — a second copy of the predicates"
done

# =================================================================================================
CASE="unknown-boot-disk-refuses"
# THE FAIL-CLOSED DIRECTION, and the one that is easy to get backwards. usr/lib/novadeck/on-boot-disk
# fails OPEN when /run/novadeck/boot is missing, because a single-disk device must still mount its
# own /home. Here the same absence has to mean "assume it IS the system disk", or a degraded
# initramfs turns into an erased card. Run against a sandbox where the file cannot exist.
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT

# THE HANDOFF IS key=value, NOT A PATH — the whole reason this case exists. Reading the file as a
# device node made storage_boot_disk answer "unknown" for every device, which the old
# short-circuit then turned into "this card is system storage". HW-caught 2026-09-02 on an
# internally-installed device: `automount.sh: skipping /dev/mmcblk0p1: this system runs from it`.
# The stub for storage_disk_of stands in for block devices this host does not have.
printf 'slot=A\nsource=grub\nroot=/dev/mmcblk9p4\nvar=/dev/mmcblk9p6\n' >"$W/boot"
out="$(NOVADECK_BOOTINFO="$W/boot" bash -c '
  . '"$LIB"'
  storage_disk_of() { printf "%s\n" "${1##*/}" | sed "s/p[0-9]*$//"; }
  storage_boot_disk' 2>/dev/null | tail -1)"
[ "$out" = mmcblk9 ] \
  && ok "root= is parsed out of the key=value handoff (mmcblk9p4 -> mmcblk9)" \
  || bad "the handoff resolved to '$out', expected mmcblk9 — the file is key=value, not a path"

# The seam name must be the one on-boot-disk already uses, or the two files disagree about where
# the boot disk is written down.
grep -q 'NOVADECK_BOOTINFO' "$LIB" && grep -q 'NOVADECK_BOOTINFO' "$ROOT/rootfs/overlay/usr/lib/novadeck/on-boot-disk" \
  && ok "both readers use the NOVADECK_BOOTINFO seam" \
  || bad "the seam name does not match on-boot-disk's"

# Fail-closed, but only when NOTHING resolves: no handoff AND a mount table that answers nothing.
# findmnt is stubbed to silence rather than removed from PATH — bash substitutes a default PATH when
# the environment has none, so `env -i` does NOT stop it running, and a first attempt at this case
# passed against the HOST's real mounts while asserting nothing.
out="$(NOVADECK_BOOTINFO=/nonexistent bash -c '
  . '"$LIB"'
  findmnt() { :; }
  storage_is_system_disk mmcblk9 && echo REFUSED || echo ALLOWED' 2>/dev/null | tail -1)"
[ "$out" = REFUSED ] \
  && ok "nothing resolvable at all -> treated as the system disk" \
  || bad "answered '$out' with no handoff and no mount table — that must fail closed"

# And the case the first version got wrong: no handoff, but a mount table that plainly says the
# system runs from another disk. That card is eligible.
out="$(NOVADECK_BOOTINFO=/nonexistent bash -c '
  . '"$LIB"'
  findmnt() { case "$*" in *--target\ /) echo /dev/sda15 ;; *) echo /dev/sda19 ;; esac; }
  storage_disk_of() { printf "%s\n" "${1##*/}" | sed -e "s/p[0-9]*$//" -e "s/[0-9]*$//"; }
  storage_is_system_disk mmcblk9 && echo REFUSED || echo ALLOWED' 2>/dev/null | tail -1)"
[ "$out" = ALLOWED ] \
  && ok "a missing handoff does not condemn a card the mount table clears" \
  || bad "answered '$out' — a card is being refused because one optional hint is absent"

# =================================================================================================
CASE="mounted-detection-actually-works"
# BEHAVIOURAL, not a grep, because the grep version of this suite passed while the predicate was
# inverted. The original implementation piped a while-loop into `grep -q`; with set -euo pipefail
# the early-exiting grep SIGPIPEs the loop and pipefail reports failure, so "something is mounted"
# came back as "nothing is mounted" — the one answer that matters. It wiped a card on 2026-09-02.
mounted_says() { # <stub findmnt output> -> MOUNTED|CLEAR
  NOVADECK_BOOTINFO=/nonexistent bash -c '
    set -euo pipefail
    . '"$LIB"'
    findmnt() { printf "%s\n" "'"$1"'"; }
    storage_disk_of() { printf "%s\n" "${1##*/}" | sed -e "s/p[0-9]*$//"; }
    storage_is_mounted mmcblk0 && echo MOUNTED || echo CLEAR' 2>/dev/null | tail -1
}
[ "$(mounted_says /dev/mmcblk0p1)" = MOUNTED ] \
  && ok "a mounted partition of the disk is detected" \
  || bad "storage_is_mounted said CLEAR for a mounted card — the inverted-predicate bug is back"
[ "$(mounted_says /dev/sda19)" = CLEAR ] \
  && ok "a mount on another disk is not confused for this one" \
  || bad "storage_is_mounted claimed a foreign mount belongs to this disk"
# set -e must not be able to kill the caller on the CLEAR path either: the formatter runs under
# `set -e` and calls this in a plain statement.
[ "$(mounted_says '')" = CLEAR ] \
  && ok "an empty mount table answers CLEAR without aborting the caller" \
  || bad "an empty mount table did not answer CLEAR"

# =================================================================================================
CASE="format-unmounts-before-it-wipes"
# The refusal was replaced by an unmount, because a card is ALWAYS mounted by our own automount by
# the time anyone asks to format it — "refuse if mounted" was unreachable in practice and left
# nothing guarding wipefs. Order matters: the unmount has to precede the first destructive command.
# CODE LINES ONLY — both words appear in the comments explaining why this order exists, and a
# comment matched first is how this case failed on a file that was already correct.
u=$(grep -nE '^[^#]*umount "\$mnt"' "$FMT" | head -1 | cut -d: -f1)
w=$(grep -nE '^[^#]*wipefs' "$FMT" | head -1 | cut -d: -f1)
[ -n "$u" ] && [ -n "$w" ] && [ "$u" -lt "$w" ] \
  && ok "unmount (line $u) runs before the first wipefs (line $w)" \
  || bad "wipefs is not preceded by the unmount loop — signatures can be erased under a live mount"
grep -q 'refusing to erase a filesystem still in use' "$FMT" \
  && ok "a failed unmount is fatal" || bad "a failed unmount does not abort the format"
grep -q 'storage_is_mounted "\$DISK" && die' "$FMT" \
  && ok "and a still-mounted disk is refused after the unmount pass" \
  || bad "nothing re-checks the disk after unmounting"

# =================================================================================================
CASE="the-mounter-does-not-announce-to-the-client"
# THE MOUNTER MOUNTS; IT DOES NOT ADOPT. steam://addlibraryfolder was added while the missing
# Format action was unexplained, and it does more than tell the client something — adding a library
# folder CREATES a SteamLibrary on the card, so every card ever inserted became a Steam library,
# including one belonging to another system. A mounted card with no library is supposed to appear
# as a drive that OFFERS to be formatted; announcing it silently converted that case into the other
# one. The client enumerates over UDisks2 unaided (GetPotentialFolders returns the card), and the
# whole Settings > Storage story was exercised on hardware with this code not running.
# CODE LINES ONLY. The comment that replaced it explains what was removed and names the URL to do
# so, and a whole-file grep matches that prose — the fourth time in this suite that a comment has
# failed a correct file. Strip comments before asserting about code.
code() { sed 's,#.*,,' "$1"; }
code "$AUTO" | grep -q 'addlibraryfolder' \
  && bad "the mounter announces to the client again — that creates a library on every inserted card" \
  || ok "no steam://addlibraryfolder: mounting a card does not make it a library"
code "$AUTO" | grep -qE 'systemd-escape|urllib\.parse\.quote|systemd-run' \
  && bad "the announce machinery is back in code (escaping, encoding or systemd-run)" \
  || ok "and none of the machinery it needed survives"

# =================================================================================================
CASE="udev-rule-is-narrow"
# THIS LINE HAS BEEN WRONG IN BOTH DIRECTIONS, so the suite now pins the direction that survives
# both cases. Matching `change` mounts a freshly formatted card (its signature arrives as a change),
# and it ALSO remounts a card the instant anyone unmounts it — the kernel emits a change on close of
# a writable block device, which is what an unmount is. That made the client's Unmount useless
# (HW-caught 2026-09-03). The format case moved into the formatter, which knows what it just did.
grep -q 'ACTION!="add|remove"' "$UDEV" \
  && ok "acts on add|remove only (a change is also what an unmount looks like)" \
  || bad "the rule acts on change — every unmount will remount the card and Eject cannot work"
grep -q 'ACTION!="add|change|remove"' "$UDEV" \
  && bad "change is matched again — this is the regression that broke Unmount" \
  || ok "and change specifically is not matched"
code "$FMT" | grep -q '/usr/lib/novadeck/storage/automount.sh add' \
  && ok "the formatter mounts the card itself, which is what matching change used to buy" \
  || bad "nothing mounts a freshly formatted card — the case that put change in the rule is back"
# FATAL, not best-effort, and upstream's own helper is the authority: `exit 5` on a failed
# post-format mount. The client has a string for it — "formatted correctly, but it failed to mount
# with the system running. A reboot is required" — which is never shown if the code is swallowed.
code "$FMT" | grep -q 'but it could not be mounted" 5' \
  && ok "a failed post-format mount exits 5, which is how the user is told to reboot" \
  || bad "the post-format mount failure is swallowed — the client cannot report it"
grep -q 'KERNEL!="mmcblk\*p\*"' "$UDEV" \
  && ok "matches SD/MMC partitions only" \
  || bad "the rule does not restrict to mmcblk*p*"
grep -qE 'KERNEL=="?sd\*|sd\[a-z\]' "$UDEV" \
  && bad "the rule matches sd* — that is the internal UFS on this hardware, not removable media" \
  || ok "does not match sd* (the vendor's internal storage)"
grep -q 'novadeck-automount@%k.service' "$UDEV" \
  && ok "hands the work to the templated unit" \
  || bad "the rule does not start novadeck-automount@%k.service"
grep -q 'ExecStart=/usr/lib/novadeck/storage/block-event.sh add %i' "$UNIT" \
  && ok "the unit runs the shipped automount path" \
  || bad "the unit's ExecStart does not match the shipped script"

# THE COLD-BOOT CASE, which the hotplug case hides. Mounting is a D-Bus call to a bus-activated
# service, so it needs a BUS — and with DefaultDependencies=no and no ordering, a card already in
# the slot at power-on fired this ~8s before dbus-broker was ready. busctl never reached udisks:
# failed unit, unmounted card, every boot with a card in (HW-caught 2026-09-03).
grep -qE '^After=.*dbus\.socket' "$UNIT" \
  && ok "ordered After=dbus.socket (a bus-activated call needs a bus first)" \
  || bad "no After=dbus.socket — at cold boot this runs before dbus-broker and cannot mount"
grep -qE '^Wants=.*dbus\.socket' "$UNIT" \
  && ok "and Wants= it, so the socket is in the transaction rather than merely ordered against" \
  || bad "After= without Wants= — ordering against a unit nothing pulled in is not ordering"

# =================================================================================================
CASE="a-mount-failure-names-its-own-reason"
# The failure above reported "udisks refused to mount", which was false: udisks never saw the call.
# stderr was folded into the stdout pipe and sed away, so every distinct failure — no bus, no such
# object, a polkit refusal — arrived as the same wrong sentence.
grep -q "log \"udisks refused to mount" "$AUTO" \
  && bad "the old blanket message is back — it names udisks for failures udisks never saw" \
  || ok "the failure path no longer blames udisks for everything"
code "$AUTO" | grep -q '2>"\$err"' \
  && ok "busctl's stderr is captured instead of folded into the mountpoint pipe" \
  || bad "stderr is not captured separately — the reason is discarded before it can be logged"
code "$AUTO" | grep -q 'could not mount \$DEVICE: \${reason' \
  && ok "and the captured reason is what gets logged" \
  || bad "the captured stderr is never logged"

# =================================================================================================
CASE="only-ext4-is-automounted"
# Upstream's reason, verbatim: "We need symlinks for Steam for now, so only automount ext4 as that's
# what Steam will format". A vfat or exfat card cannot host a library — no symlinks, no casefolding
# — and mounting one gives the user a mount they cannot use in the exact place the client is trying
# to tell them the card needs formatting.
code "$AUTO" | grep -q 'FSTYPE' \
  && ok "the mounter reads the filesystem type before mounting" \
  || bad "nothing checks the filesystem type — any card mounts"
code "$AUTO" | grep -q '"\$FSTYPE" != ext4' \
  && ok "and refuses anything that is not ext4" \
  || bad "the ext4 restriction is not applied"
# EXIT 0, where upstream exits 2: inserting a foreign card is normal, and a non-zero exit here
# leaves a failed unit for the rest of the boot.
sed -n '/not ext4 — a Steam library/,+1p' "$AUTO" | grep -q 'exit 0' \
  && ok "and stands down with exit 0 rather than leaving a failed unit" \
  || bad "a foreign card leaves a failed unit — that is a fault report for a normal action"

# =================================================================================================
CASE="one-lock-keeps-the-formatter-and-the-mounter-apart"
# MEASURED, after two rounds of treating the symptom. During a validated format the mounter ran
# twice on the device being formatted — once before the partition existed, once while mkfs was
# writing it ("fsconfig() failed: Can't open blockdev"). Both processes owned one device. Upstream
# takes a shared flock in both paths for exactly this; we had none.
code "$LIB" | grep -q 'storage_lock()' \
  && ok "there is one lock helper, shared by both scripts" \
  || bad "no storage_lock — nothing stops a format and an automount running together"
code "$LIB" | grep -q 'flock -n 9' \
  && ok "and it is non-blocking, so a caller that cannot have it moves on" \
  || bad "the lock blocks — a udev-triggered unit would wait instead of standing down"
code "$FMT" | grep -q 'storage_lock "\$PARTBASE"' \
  && ok "the formatter takes it" || bad "the formatter does not take the lock"
code "$EVT" | grep -q 'storage_lock "\$DEVBASE"' \
  && ok "the udev entry point takes it too" || bad "the udev entry point does not take the lock"
# EXIT 0, not a failure: a format in progress is a reason not to mount, and the formatter mounts the
# card itself when it is done. A non-zero exit here is a failed unit for a healthy system.
sed -n '/a format is in progress/,+1p' "$EVT" | grep -q 'exit 0' \
  && ok "and stands down with exit 0, not a failed unit" \
  || bad "the mounter reports failure when it merely stood aside"
# ORDER: the lock must precede the first thing that touches the device, which is the unmount pass.
l_ln=$(grep -nE '^storage_lock "\$PARTBASE"' "$FMT" | head -1 | cut -d: -f1)
u_ln=$(grep -nE '^[^#]*umount "\$mnt"' "$FMT" | head -1 | cut -d: -f1)
[ -n "$l_ln" ] && [ -n "$u_ln" ] && [ "$l_ln" -lt "$u_ln" ] \
  && ok "taken (line $l_ln) before the first thing that touches the device (line $u_ln)" \
  || bad "the lock is taken after the device is already being worked on"

# BEHAVIOURAL, because a lock that does not exclude is worse than none: it reads as protection.
# Held in one process, attempted in another, against a sandbox /run.
# The first version of this case reported HELD/FREE from both the outer and inner shell, so "the
# parent could not take the lock" and "the child took it as well" were the same string — it failed
# against a lock that works. Each side now names itself, and both are asserted.
sed "s,/run/novadeck,$W/run/novadeck,g" "$LIB" > "$W/lib.sh"
lock_out="$(bash -c '. '"$W/lib.sh"'
    if storage_lock testpart; then
        echo PARENT_ACQUIRED
        bash -c ". '"$W/lib.sh"'; storage_lock testpart && echo CHILD_ACQUIRED || echo CHILD_REFUSED"
    else
        echo PARENT_FAILED
    fi' 2>/dev/null)"
case "$lock_out" in
  *PARENT_ACQUIRED*CHILD_REFUSED*) ok "a second holder is refused while the first has it" ;;
  *PARENT_ACQUIRED*CHILD_ACQUIRED*) bad "storage_lock does not exclude — it reads as protection while providing none" ;;
  *) bad "storage_lock could not be taken at all in the sandbox ($lock_out) — the case proves nothing" ;;
esac
seam="$(bash -c 'NOVADECK_STORAGE_LOCK_HELD=testpart; . '"$W/lib.sh"'; storage_lock testpart && echo PASS || echo BLOCKED' 2>/dev/null | tail -1)"
[ "$seam" = PASS ] \
  && ok "and the parent-holds-it seam lets the formatter's own child through" \
  || bad "the seam does not work — the formatter's post-format mount would be refused"

