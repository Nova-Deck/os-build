CASE="the-formatter-speaks-the-clients-argument-vocabulary"
# The client builds the command line itself (steamui.so: `--device <dev> --label '<name>' --force`,
# plus --enable-duplicate-detection when "Run validation tests" is ticked, which for SD media is
# ticked BY DEFAULT). The parser used to `die "unknown argument"` on all three, so the first format
# the client ever attempted would have failed on --force alone — with the env gate above now open,
# that is a live path rather than a hypothetical one.
# BEHAVIOURAL, against a copy whose absolute source line points at the repo, because the exit code
# is the whole assertion: 22 is "I do not understand you", and anything else means we parsed it.
FCOPY="$W/format-device.sh"
sed "s,^\. /usr/lib/novadeck/storage/lib-storage.sh,. $LIB," "$FMT" > "$FCOPY"; chmod +x "$FCOPY"
arg_exit() { NOVADECK_BOOTINFO=/nonexistent "$FCOPY" "$@" >/dev/null 2>&1; echo $?; }

# /dev/null is a CHARACTER device, so a root run stops at the block-device check and a non-root run
# stops at the root check. Neither writes anything, and neither is 22.
for a in --force --skip-validation --full --quick; do
  [ "$(arg_exit "$a" --device /dev/null)" != 22 ] \
    && ok "$a is accepted" \
    || bad "$a is rejected as an unknown argument — a format sending it would fail on its first try"
done
[ "$(arg_exit --version)" = 0 ] \
  && ok "--version answers, so a caller can tell what this understands" \
  || bad "--version is not answered"
[ "$(arg_exit --no-such-flag)" = 22 ] \
  && ok "and an argument we really do not know is still refused" \
  || bad "an unknown argument no longer refuses — the parser accepts anything"

# THE OPTION SET IS UPSTREAM'S, WITH NOTHING ADDED. A helper whose CLI matches the one it was ported
# from can be diffed against it in one glance; every option we bolt on is one the comparison no
# longer makes. --auto lived here and moved to steamos-format-sdcard, where our divergence belongs.
opts="$(sed -n 's/^ *\(--[a-z|-]*\)).*/\1/p' "$FMT" | tr '|' '\n' | grep -c .)"
for o in --version --force --skip-validation --full --quick --owner --device --label; do
  sed -n 's/^ *\(--[a-z|-]*\)).*/\1/p' "$FMT" | tr '|' '\n' | grep -qx -- "$o" \
    && ok "handles $o, as upstream does" \
    || bad "$o is missing — upstream's getopt has it"
done
[ "$opts" = 8 ] \
  && ok "and handles nothing else (8 long options, upstream's exact set)" \
  || bad "$opts long options handled, upstream has 8 — something was added to a copied contract"

