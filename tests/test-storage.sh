grep -q 'mkfs\.ext4 .*-m 0' "$FMT" \
  && ok "no reserved blocks (-m 0)" || bad "-m 0 is missing"
grep -q 'OWNER="1000:1000"' "$FMT" \
  && ok "the card ends up owned by deck" || bad "no default owner — the card would mount root-owned"
grep -q 'label: gpt' "$FMT" \
  && ok "GPT with a single partition" || bad "no GPT table is written"

