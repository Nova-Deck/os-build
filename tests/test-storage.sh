  && ok "and that check is skipped during boot, where the events legitimately arrive late" \
  || bad "the recency check would refuse cold-boot cards"
# THE SPLIT UPSTREAM GETS FOR FREE. Their entry point asks "does this udev event deserve a mount"
# (lock, settle, recency); their mounter asks none of it, and their formatter calls the mounter. One
# file playing both parts must tell them apart, or the recency check refuses the formatter's own
# post-format mount — a card in the slot for minutes was not "inserted recently" — and an unmounted
# card is what makes the client say the drive still needs formatting. HW-caught 2026-09-03.
# THE SPLIT ITSELF IS THE ASSERTION. The mounter must contain no event-filtering code, because the
# formatter calls it directly and none of those questions apply to a filesystem just created on
# purpose. Held in one file behind a guard, forgetting the guard broke this feature twice in an
# afternoon; held in two files there is nothing to forget.
for c in 'udevadm settle' 'TimeMediaDetected' 'storage_lock'; do
  code "$AUTO" | grep -q "$c" \
    && bad "the mounter still contains '$c' — it will misapply it to the formatter's own call" \
    || ok "the mounter contains no '$c'"
done
code "$EVT" | grep -q 'exec "\$MOUNTER" add' \
  && ok "and the entry point hands off to the mounter by exec, keeping the lock held" \
  || bad "the entry point does not exec the mounter"
code "$AUTO" | grep -q 'fsck.ext4 -y' \
  && ok "the filesystem is repaired before it is mounted" \
  || bad "no fsck — a dirty card mounts unrepaired"
code "$AUTO" | grep -q 'OPTS="\$OPTS,ro"' \
  && ok "and one that cannot be repaired mounts read-only" \
  || bad "an unrepairable card would still mount read-write"
code "$AUTO" | grep -q 'options s "\$OPTS"' \
  && ok "the options reach udisks" || bad "OPTS is computed and then not passed"
code "$AUTO" | grep -q 'setpriv --clear-groups' \
